#!/usr/bin/env bash
#
# Generates the iOS .strings tables from the Android string resources.
#
# Two hand-maintained copies of a hundred and seventy strings drift within a
# week, and the drift is invisible: a key present on one platform and absent on
# the other renders as the key itself, which reads as a placeholder somebody
# forgot rather than a missing translation.
#
# Two things are converted, and they are why this is a script rather than a
# copy:
#
#   Format specifiers. Android writes positional Java specifiers — %1$s, %1$d —
#   and Foundation wants %@ and %lld. Getting that wrong is not a rendering
#   glitch: a %d against a 64-bit Int on iOS reads the wrong half of the word.
#
#   Escapes. Android XML needs \' inside an unquoted value; a .strings file does
#   not, and leaving it in renders the backslash.
#
# Plurals are deliberately *not* generated. Android's <plurals> and Foundation's
# .stringsdict have different category rules and a different file format, and a
# mechanical translation between them would be wrong for Arabic — which has six
# categories where English has two. The four `ago_*` plurals are the only ones,
# and iOS renders those from `RelativeDateTimeFormatter` instead.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
android="$here/androidApp/src/main/res"
ios="$here/iosApp/iosApp"

convert() {
  sed -e 's/&amp;/\&/g' -e 's/&lt;/</g' -e 's/&gt;/>/g' "$1" \
    | grep -oE '<string name="[a-z_]+">[^<]*</string>' \
    | sed -E 's|<string name="([a-z_]+)">(.*)</string>|"\1" = "\2";|' \
    | sed -E 's/%1\$s/%@/g; s/%2\$s/%@/g' \
    | sed -E 's/%1\$02d/%02lld/g; s/%2\$02d/%02lld/g' \
    | sed -E 's/%1\$d/%lld/g; s/%2\$d/%lld/g; s/%3\$d/%lld/g' \
    | tr -d '\\'
}

header() {
  cat <<'EOF'
/*
 * Generated by tools/gen-ios-strings.sh from the Android string resources.
 * Do not edit — run `make ios-strings`.
 */

EOF
}

mkdir -p "$ios/en.lproj" "$ios/ar.lproj"

{
  header
  convert "$android/values/strings.xml"
  cat <<'EOF'

/* Not in the Android chrome — iOS draws a back chevron where Compose relies on
   the system gesture, and a chevron needs a label for VoiceOver. */
"action_back" = "Back";
EOF
} > "$ios/en.lproj/Localizable.strings"

{
  header
  convert "$android/values-ar/strings.xml"
  printf '\n"action_back" = "رجوع";\n'
} > "$ios/ar.lproj/Localizable.strings"

# The unlocalised copy Xcode falls back to when a device language matches no
# .lproj at all.
cp "$ios/en.lproj/Localizable.strings" "$ios/Localizable.strings"

en=$(grep -c '^"' "$ios/en.lproj/Localizable.strings")
ar=$(grep -c '^"' "$ios/ar.lproj/Localizable.strings")
echo "en: $en strings, ar: $ar strings"

# A mismatch means somebody added a string to one language and not the other,
# which on Android degrades to the English fallback and on iOS renders the key.
# Loud rather than silent.
if [ "$en" -ne "$ar" ]; then
  echo "WARNING: the two tables disagree — a string is missing a translation" >&2
fi
